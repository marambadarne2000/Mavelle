ALTER TABLE products ADD COLUMN version BIGINT NOT NULL DEFAULT 0;
ALTER TABLE products ADD CONSTRAINT product_sku_normalized CHECK (sku = upper(trim(sku)));
CREATE TABLE inventory_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id),
    actor_id BIGINT NOT NULL REFERENCES users(id),
    quantity_delta INTEGER NOT NULL CHECK (quantity_delta <> 0),
    reason VARCHAR(240) NOT NULL CHECK (length(trim(reason)) > 0),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX inventory_movements_product_id_idx ON inventory_movements(product_id, id DESC);
