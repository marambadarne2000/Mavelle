UPDATE order_items i SET company_id=p.company_id FROM products p WHERE p.id=i.product_id;
ALTER TABLE order_items ALTER COLUMN company_id SET NOT NULL;
CREATE TABLE merchant_orders (
 order_id BIGINT NOT NULL REFERENCES orders(id),
 company_id BIGINT NOT NULL REFERENCES companies(id),
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','SHIPPED','DELIVERED','CANCELLED')),
 version BIGINT NOT NULL DEFAULT 0,
 PRIMARY KEY(order_id,company_id)
);
INSERT INTO merchant_orders(order_id,company_id,status) SELECT DISTINCT i.order_id,i.company_id,o.status FROM order_items i JOIN orders o ON o.id=i.order_id;
CREATE INDEX merchant_orders_company_idx ON merchant_orders(company_id,order_id);
CREATE TABLE merchant_order_history (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id BIGINT NOT NULL, company_id BIGINT NOT NULL,
 actor_id BIGINT NOT NULL REFERENCES users(id),
 from_status VARCHAR(20) NOT NULL, to_status VARCHAR(20) NOT NULL,
 reason VARCHAR(240) NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(order_id,company_id) REFERENCES merchant_orders(order_id,company_id)
);
CREATE TABLE customer_profiles (
 user_id BIGINT PRIMARY KEY REFERENCES users(id),
 full_name VARCHAR(120) NOT NULL DEFAULT '', phone VARCHAR(40) NOT NULL DEFAULT '',
 address VARCHAR(240) NOT NULL DEFAULT '', city VARCHAR(120) NOT NULL DEFAULT ''
);
CREATE TABLE favorites (
 user_id BIGINT NOT NULL REFERENCES users(id), product_id BIGINT NOT NULL REFERENCES products(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(user_id,product_id)
);
CREATE TABLE store_offers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, company_id BIGINT NOT NULL REFERENCES companies(id),
 title VARCHAR(160) NOT NULL, body VARCHAR(1000) NOT NULL,
 starts_at TIMESTAMPTZ NOT NULL, ends_at TIMESTAMPTZ NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK(ends_at>starts_at)
);
CREATE INDEX store_offers_active_idx ON store_offers(company_id,ends_at);
CREATE TABLE store_messages (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 company_id BIGINT NOT NULL REFERENCES companies(id), customer_id BIGINT NOT NULL REFERENCES users(id),
 sender_id BIGINT NOT NULL REFERENCES users(id), body VARCHAR(2000) NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX store_messages_thread_idx ON store_messages(company_id,customer_id,id);
CREATE TABLE store_reviews (
 company_id BIGINT NOT NULL REFERENCES companies(id), customer_id BIGINT NOT NULL REFERENCES users(id),
 rating INTEGER NOT NULL CHECK(rating BETWEEN 1 AND 5), body VARCHAR(1500) NOT NULL,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(company_id,customer_id)
);
