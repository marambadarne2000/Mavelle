ALTER TABLE users DROP CONSTRAINT users_role_check;
ALTER TABLE users ADD CONSTRAINT users_role_check CHECK(role IN ('CUSTOMER','ADMIN','EMPLOYEE','MERCHANT'));
ALTER TABLE companies ADD COLUMN status VARCHAR(20) NOT NULL DEFAULT 'APPROVED' CHECK(status IN ('PENDING','APPROVED','SUSPENDED'));
CREATE TABLE merchant_stores (
 company_id BIGINT PRIMARY KEY REFERENCES companies(id),
 user_id BIGINT NOT NULL UNIQUE REFERENCES users(id),
 owner_name VARCHAR(120) NOT NULL,
 business_type VARCHAR(30) NOT NULL CHECK(business_type IN ('Makeup','Clothing','Games','Home','Mixed','Other')),
 registration_number VARCHAR(40) NOT NULL DEFAULT '',
 phone VARCHAR(40) NOT NULL,
 contact_email VARCHAR(254) NOT NULL,
 terms_accepted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE store_moderation_history (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 company_id BIGINT NOT NULL REFERENCES companies(id),
 actor_id BIGINT NOT NULL REFERENCES users(id),
 status VARCHAR(20) NOT NULL, reason VARCHAR(500) NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
