CREATE TABLE support_tickets (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 requester_id BIGINT NOT NULL REFERENCES users(id),
 subject VARCHAR(160) NOT NULL,
 category VARCHAR(20) NOT NULL CHECK(category IN ('ORDER','ACCOUNT','STORE','TECHNICAL','OTHER')),
 status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK(status IN ('OPEN','IN_PROGRESS','RESOLVED')),
 version BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 status_changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX support_requester_idx ON support_tickets(requester_id,updated_at DESC,id DESC);
CREATE INDEX support_status_idx ON support_tickets(status,updated_at DESC,id DESC);
CREATE TABLE support_messages (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ticket_id BIGINT NOT NULL REFERENCES support_tickets(id),
 sender_id BIGINT NOT NULL REFERENCES users(id),
 body VARCHAR(2000) NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX support_messages_ticket_idx ON support_messages(ticket_id,id);
CREATE INDEX support_messages_sender_idx ON support_messages(sender_id,created_at DESC);
CREATE TABLE notification_reads (
 user_id BIGINT NOT NULL REFERENCES users(id),
 event_key VARCHAR(100) NOT NULL,
 read_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(user_id,event_key)
);
