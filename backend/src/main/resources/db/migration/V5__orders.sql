CREATE TABLE orders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_number VARCHAR(40) NOT NULL UNIQUE,
 user_id BIGINT NOT NULL REFERENCES users(id),
 total_price NUMERIC(18,2) NOT NULL CHECK(total_price>0),
 currency VARCHAR(3) NOT NULL DEFAULT 'ILS',
 status VARCHAR(20) NOT NULL CHECK(status IN ('PENDING','SHIPPED','DELIVERED','CANCELLED')),
 shipping JSONB NOT NULL,
 idempotency_key VARCHAR(64) NOT NULL,
 request_fingerprint VARCHAR(64) NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(user_id,idempotency_key)
);
CREATE INDEX orders_user_created_idx ON orders(user_id,created_at DESC,id DESC);
CREATE TABLE order_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id BIGINT NOT NULL REFERENCES orders(id),
 product_id BIGINT NOT NULL REFERENCES products(id),
 sku VARCHAR(80) NOT NULL,
 name VARCHAR(160) NOT NULL,
 company_name VARCHAR(120) NOT NULL,
 unit_price NUMERIC(12,2) NOT NULL CHECK(unit_price>0),
 quantity INTEGER NOT NULL CHECK(quantity BETWEEN 1 AND 99),
 UNIQUE(order_id,product_id)
);
ALTER TABLE inventory_movements ADD COLUMN order_id BIGINT REFERENCES orders(id);
CREATE INDEX inventory_movements_order_idx ON inventory_movements(order_id);
