CREATE TABLE demo_payments (
 order_id BIGINT PRIMARY KEY REFERENCES orders(id),
 status VARCHAR(20) NOT NULL CHECK(status IN ('CAPTURED','PARTIAL_REFUND','REFUNDED')),
 amount_agorot BIGINT NOT NULL CHECK(amount_agorot>0),
 refunded_agorot BIGINT NOT NULL DEFAULT 0 CHECK(refunded_agorot>=0 AND refunded_agorot<=amount_agorot),
 commission_basis_points INTEGER NOT NULL DEFAULT 500,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE return_requests (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id BIGINT NOT NULL,
 company_id BIGINT NOT NULL,
 customer_id BIGINT NOT NULL REFERENCES users(id),
 kind VARCHAR(10) NOT NULL CHECK(kind IN ('CANCEL','RETURN')),
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','COMPLETED','REJECTED')),
 reason VARCHAR(1000) NOT NULL,
 resolution VARCHAR(1000),
 actor_id BIGINT REFERENCES users(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 resolved_at TIMESTAMPTZ,
 FOREIGN KEY(order_id,company_id) REFERENCES merchant_orders(order_id,company_id)
);
CREATE UNIQUE INDEX return_one_active ON return_requests(order_id,company_id) WHERE status IN ('PENDING','COMPLETED');
CREATE TABLE demo_ledger (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id BIGINT REFERENCES orders(id),
 company_id BIGINT NOT NULL REFERENCES companies(id),
 event VARCHAR(20) NOT NULL CHECK(event IN ('SALE','REFUND','SUBSCRIPTION')),
 gross_agorot BIGINT NOT NULL,
 fee_agorot BIGINT NOT NULL,
 merchant_agorot BIGINT NOT NULL,
 event_key VARCHAR(120) NOT NULL UNIQUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK(gross_agorot=fee_agorot+merchant_agorot)
);
CREATE TABLE demo_subscriptions (
 company_id BIGINT PRIMARY KEY REFERENCES companies(id),
 status VARCHAR(20) NOT NULL CHECK(status IN ('ACTIVE','CANCELLED')),
 consent_at TIMESTAMPTZ NOT NULL,
 period_start DATE NOT NULL,
 period_end DATE NOT NULL,
 cancelled_at TIMESTAMPTZ
);
